/**
 * @file exipConfig.h
 * @brief Configuration of the EXIP library
 *
 * The configuration is assembled from, in order of precedence:
 * -# macros defined on the compiler command line;
 * -# EXIP_USER_CONFIG_FILE, if defined: a header (for example "my_exip_config.h")
 *    with the application's settings, for builds that do not use CMake (Arduino,
 *    PlatformIO, other build systems);
 *    Arduino and ESP-IDF builds (ARDUINO or ESP_PLATFORM defined) without a CMake
 *    configuration get exip_arduino_config.h, so that the library and the sketch, which
 *    are compiled with different flags, agree on the types (EXIP_NO_ARDUINO_CONFIG
 *    turns this off);
 * -# exip_build_config.h, generated by CMake from the EXIP_CFG_* options, when
 *    EXIP_HAVE_BUILD_CONFIG is defined (the CMake targets define it);
 * -# exipConfigDefaults.h, which gives every remaining setting its default and
 *    checks the result.
 * Every setting is guarded by #ifndef, so the first definition wins.
 */

#ifndef EXIPCONFIG_H_
#define EXIPCONFIG_H_

#if !defined(EXIP_USER_CONFIG_FILE) && !defined(EXIP_HAVE_BUILD_CONFIG) && \
    !defined(EXIP_NO_ARDUINO_CONFIG) && (defined(ARDUINO) || defined(ESP_PLATFORM))
#  define EXIP_USER_CONFIG_FILE "exip_arduino_config.h"
#endif

#if defined(EXIP_USER_CONFIG_FILE)
#  include EXIP_USER_CONFIG_FILE
#endif

#if defined(EXIP_HAVE_BUILD_CONFIG)
#  include "exip_build_config.h"
#endif

#include "exipConfigDefaults.h"
#include "exipPortability.h"

#endif /* EXIPCONFIG_H_ */
